export interface WellData {
  id: string; // e.g., 'BGW-01'
  pad: string; // e.g., 'Pad-01'
  row: number; // grid row 0-4
  col: number; // grid col 0-6
  status: WellStatus;
  cyclePhase: WellCyclePhase;
  cycleNumber: number;
  daysSinceInjection: number; // Days since last steam injection completed
  bottomholeTempC: number; // Estimated Current Bottomhole Temp (°C)
  oilRateBOPD: number;
  steamOilRatio: number; // m3/m3 or bbl/bbl
  reservoirTempC: number;
  crudeViscosityCP: number;
  polishedRodLoadLbs: number; // Peak load
  minRodLoadLbs: number; // Min load (critical for rod float risk)
  strokeRateSPM: number;
  pumpFillagePct: number; // Pump fillage efficiency %
  rodLoadStatus: 'NOMINAL' | 'HIGH LOAD' | 'ROD FLOAT' | 'COMPRESSION' | 'INJ / SOAK';
  rodFloatingRisk: boolean;
  alertReason?: string;
}

